"""Write the posts per institution from "docs/allocation per institution.csv"
into apps-script/Code.gs (the ALLOCATIONS list, between the BEGIN/END lines),
and the posts kept back for further allocation from "docs/reserved posts.csv"
(the RESERVED_POSTS list). The institutions and the reserved posts together
must add up to TOTAL_POSTS (611).

Each institution is matched to the facility name applicants chose on the
application form (from docs/EC_EPWP.csv), so that applications can be counted
per institution. Institutions that do not match are listed; they still get
their posts, and HR can pick applicants for them from the whole district.

The list is only the starting point: the first time the Selection screen is
used, the script copies it into an "Allocations" tab of the Sheet, and from
then on the tab is used (so HR can correct posts there).

Run from the project root:  python tools/build_allocations.py
"""
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "allocation per institution.csv"
RESERVED_SRC = ROOT / "docs" / "reserved posts.csv"
TOTAL_POSTS = 611
UNITS_SRC = ROOT / "docs" / "EC_EPWP.csv"
GS = ROOT / "apps-script" / "Code.gs"
BEGIN = "// BEGIN ALLOCATIONS (generated by tools/build_allocations.py - do not edit by hand)"
END = "// END ALLOCATIONS"

# District names in the allocation list -> district as stored in applications.
DISTRICTS = {
    "alfred nzo district": "Alfred Nzo District",
    "amathole district": "Amathole District",
    "buffalo city": "Buffalo City Metro",
    "buffalo city metro": "Buffalo City Metro",
    "head office": "Buffalo City Metro",
    "chris hani": "Chris Hani District",
    "joe gqabi": "Joe Gqabi District",
    "joe gqabi district": "Joe Gqabi District",
    "chris hani district": "Chris Hani District",
    "or tambo district": "OR Tambo District",
    "sarah baartman district": "Sarah Baartman District",
    "n mandela bay mm": "N Mandela Bay MM",
    "or tambo": "OR Tambo District",
    "sarah baartman": "Sarah Baartman District",
}
# Spelling corrections to the allocation list.
NAME_FIXES = {
    "Livingtsone Hospital": "Livingstone Hospital",
    "Livingtsone Hospital (PE Provincial)": "PE Provincial Hospital",
}
# Institution names spelt differently in the allocation list than on the form.
SAME_FACILITY = {
    "L Grey Hosp": "Lady Grey Hosp",
    "Steynsbyurg": "Steynsbyurg Hosp",
    "Port Alfred": "Port Alfred Hospital",
}


def key(s):
    """Same idea as facilityKey_ in Code.gs."""
    s = s.lower().replace("&", " and ")
    s = re.sub(r"\bcommunity health cent(er|re)\b", "chc", s)
    s = re.sub(r"\b(hospitals?|hosp)\b\.?", "hosp", s)
    return re.sub(r"[^a-z0-9]", "", s)


# Facilities on the application form, per district.
form = {}
with UNITS_SRC.open(encoding="cp1252", newline="") as fh:
    for row in csv.DictReader(fh, delimiter=";"):
        d = row["District"].strip()
        d = "Buffalo City Metro" if d == "Head Office" else d
        f = row["Facility"].strip()
        lm = row["Local Municipality"].strip()
        if d and f:
            form.setdefault(key(f), []).append((d, f, lm))

# Posts kept back for further allocation, for example from duplicate lines
# removed from the allocation list. A removed line is also left out of the
# institutions if it is still in the allocation list.
reserved, removed = [], {}
with RESERVED_SRC.open(encoding="cp1252", newline="") as fh:
    for row in csv.DictReader(fh, delimiter=";"):
        district = DISTRICTS[row["District"].strip().lower()]
        line = re.sub(r"\s+", " ", row["Duplicate line removed from the allocation list"] or "").strip()
        reserved.append([district, int(row["Posts"]), line, (row["Same hospital as"] or "").strip(),
                         (row["Reason"] or "").strip(), (row["Allocated to (institution)"] or "").strip(),
                         (row["Allocated on"] or "").strip()])
        if line:
            removed[(district, key(line))] = True

rows, unmatched, seen = [], [], {}
with SRC.open(encoding="cp1252", newline="") as fh:
    for row in csv.DictReader(fh, delimiter=";"):
        district = DISTRICTS[row["District"].strip().lower()]
        name = re.sub(r"\s+", " ", row["Facility Name"]).strip()
        name = NAME_FIXES.get(name, name)
        posts = int(row["Allocation"])
        if (district, key(name)) in removed:
            continue
        target = SAME_FACILITY.get(name, name)
        hits = form.get(key(target), [])
        hit = next((h for h in hits if h[0] == district), hits[0] if hits else None)
        facility, local = (hit[1], hit[2]) if hit else ("", "")
        if not hit:
            unmatched.append(f"{district}: {name} ({posts})")
        if facility:
            seen.setdefault(facility, []).append(name)
        rows.append([district, name, posts, facility, local])

total = sum(r[2] for r in rows)
kept = sum(r[1] for r in reserved)
if total + kept != TOTAL_POSTS:
    raise SystemExit(f"Institutions ({total}) plus reserved posts ({kept}) make {total + kept}, not {TOTAL_POSTS}.")
gs = GS.read_text(encoding="utf-8")
a, b = gs.index(BEGIN), gs.index(END)
gs = (gs[:a] + BEGIN
      + "\n// [district, institution, posts, facility on the application form, local municipality]\nvar ALLOCATIONS = "
      + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n"
      + "// Posts kept for further allocation: [district, posts, duplicate line removed, same hospital as,\n"
      + "// reason, allocated to, allocated on]\nvar RESERVED_POSTS = "
      + json.dumps(reserved, ensure_ascii=False, separators=(",", ":")) + ";\n"
      + "var TOTAL_POSTS = " + str(TOTAL_POSTS) + ";\n" + gs[b:])
GS.write_text(gs, encoding="utf-8", newline="\n")

print(f"{len(rows)} institutions with {total} posts, plus {kept} reserved = {total + kept} -> {GS}")
print("Not on the application form (no applications can be counted for them):")
for u in unmatched:
    print("  " + u)
form_facilities = {f for hits in form.values() for (_, f, _) in hits}
print("On the application form but without posts:")
for f in sorted(form_facilities - set(seen)):
    print("  " + f)
