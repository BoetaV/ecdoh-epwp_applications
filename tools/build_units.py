"""Regenerate assets/units.js (website) and the UNITS list in apps-script/Code.gs
(used by the Import tab) from docs/EC_EPWP.csv.

Run from the project root:  python tools/build_units.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "EC_EPWP.csv"
OUT = ROOT / "assets" / "units.js"
GS = ROOT / "apps-script" / "Code.gs"
BEGIN = "// BEGIN UNITS (generated by tools/build_units.py - do not edit by hand)"
END = "// END UNITS"

# Head Office is in Buffalo City, so its entry is listed under that metro.
DISTRICT_ALIASES = {"Head Office": "Buffalo City Metro"}

units = {}
# The CSV is saved by Excel as Windows-1252 with ';' separators.
with SRC.open(encoding="cp1252", newline="") as fh:
    for row in csv.DictReader(fh, delimiter=";"):
        district = row["District"].strip()
        district = DISTRICT_ALIASES.get(district, district)
        local = row["Local Municipality"].strip()
        facility = row["Facility"].strip()
        if not district or not local:
            continue
        facilities = units.setdefault(district, {}).setdefault(local, [])
        if facility and facility not in facilities:
            facilities.append(facility)

body = json.dumps(units, ensure_ascii=False, indent=1)
OUT.write_text(
    "// Generated by tools/build_units.py from docs/EC_EPWP.csv - do not edit by hand.\n"
    f"window.EPWP_UNITS = {body};\n",
    encoding="utf-8",
)
print(f"{len(units)} districts, {sum(len(v) for v in units.values())} municipalities -> {OUT}")

# The same list inside Code.gs, between the BEGIN/END UNITS lines.
gs = GS.read_text(encoding="utf-8")
a, b = gs.index(BEGIN), gs.index(END)
compact = json.dumps(units, ensure_ascii=False, separators=(",", ":"))
gs = gs[:a] + BEGIN + "\nvar UNITS = " + compact + ";\n" + gs[b:]
GS.write_text(gs, encoding="utf-8", newline="\n")
print(f"UNITS updated in {GS}")
